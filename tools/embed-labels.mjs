// Precomputes MobileCLIP S0 text embeddings for every label prompt, so the browser
// only needs the small image model. Run: cd tools && npm i && node embed-labels.mjs
import { env, AutoTokenizer, CLIPTextModelWithProjection } from "@huggingface/transformers";
import { writeFileSync } from "node:fs";
import { LABELS } from "../src/labels.js";
env.localModelPath = new URL("../models/", import.meta.url).pathname;
env.allowRemoteModels = false;
const id = "Xenova/mobileclip_s0";
const tok = await AutoTokenizer.from_pretrained(id);
const model = await CLIPTextModelWithProjection.from_pretrained(id, { dtype: "fp32" });
const rows = [], keys = [];
for (const l of LABELS) for (const p of l.prompts) { rows.push(`a photo of ${p}`); keys.push(l.key); }
const { text_embeds } = await model(tok(rows, { padding: "max_length", truncation: true }));
const emb = text_embeds.normalize().tolist();
// Store as int8 (scale 127) to keep the file small; cosine ranking is unaffected in practice.
const q = emb.map((v) => v.map((x) => Math.max(-127, Math.min(127, Math.round(x * 127)))));
const out = `// Generated by tools/embed-labels.mjs. MobileCLIP S0 text embeddings, int8, ${rows.length} prompts x ${emb[0].length}.\nexport const DIM = ${emb[0].length};\nexport const PROMPT_KEYS = ${JSON.stringify(keys)};\nexport const EMBEDS_I8 = ${JSON.stringify(q.flat())};\n`;
writeFileSync(new URL("../src/data/label-embeds.js", import.meta.url), out);
console.log(rows.length, "prompts", out.length, "bytes");
