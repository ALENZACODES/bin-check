// Builds src/data/items.js from the City of Toronto Waste Wizard open data file
// (data/waste-wizard-2023-11-27.json). Run: node tools/build-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
const raw = JSON.parse(readFileSync(new URL("../data/waste-wizard-2023-11-27.json", import.meta.url)));
const CAT = { "Oversized item": "Oversized Item", "Not Accepted ": "Not Accepted", "Not accepted": "Not Accepted", "Garbage": "Garbage Bin" };
const items = raw.map((r) => ({
  id: r.id,
  title: r.item.trim(),
  names: r.item.split("/").map((s) => s.trim()).filter(Boolean),
  bin: CAT[r.category] || r.category.trim(),
  steps: r.instructions.map((s) => s.trim()).filter(Boolean),
}));
const out = `// Generated by tools/build-data.mjs from the City of Toronto Waste Wizard open data
// (dataset "Waste Wizard Lookup Table", file dated 2023-11-27, ${items.length} items).
// Source: https://open.toronto.ca/dataset/waste-wizard-lookup-table/
export const ITEMS = ${JSON.stringify(items)};\n`;
writeFileSync(new URL("../src/data/items.js", import.meta.url), out);
console.log(items.length, "items", out.length, "bytes");
